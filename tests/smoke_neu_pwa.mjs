pruefe('unten gibt es keine Leiste, am Rand den Griff', await p.locator('.nav').count() === 0 && await p.locator('.fl-griff').count() === 1);
pruefe('die App füllt den Bildschirm genau', await Zs(p, () => Math.round(document.querySelector('.mx').getBoundingClientRect().height) === innerHeight));
await p.click('[data-a=beispiele]'); await p.waitForSelector('[data-paket]');
pruefe('Pakete werden erst auf Tippen angeboten: 2 Stück (Ohne Alkohol ist aus)', await p.locator('[data-paket]').count() === 2);
await p.click('[data-paket=getraenke-ohne-alkohol-start]'); await p.waitForSelector('.karte'); await ruhe(p);
pruefe('Startpaket: 7 Karten', await p.locator('.karte').count() === 7);
pruefe('jedes Beispiel trägt Marke und Kennung', await Zs(p, () => __mixarium.sammlung.getraenke.every((r) => r.beispiel === 'getraenke-ohne-alkohol-start' && r.uid && r.beispielPruef)));
pruefe('kein Querlaufen', await Zs(p, () => document.documentElement.scrollWidth <= innerWidth));
await p.fill('#suche', 'ingwer'); await ruhe(p);
pruefe('Suche findet über die Zutat, das Feld behält den Fokus', await p.locator('.karte').count() === 1 && await Zs(p, () => document.activeElement.id === 'suche'));
await p.fill('#suche', ''); await ruhe(p);
await p.click('.karte >> nth=0'); await p.waitForSelector('.held'); await ruhe(p);
const vor = await p.locator('.zutaten .menge').allTextContents();
await p.click('[data-a=plus]'); await p.click('[data-a=plus]'); await ruhe(p);
const nach = await p.locator('.zutaten .menge').allTextContents();
pruefe('Portionen 1 → 3 rechnet die Mengen um', vor[1] === '2 cl' && nach[1] === '6 cl', vor[1] + ' → ' + nach[1]);
await p.click('[data-e=ml]'); await ruhe(p);
pruefe('Umschalten auf ml: 6 cl → 60 ml', (await p.locator('.zutaten .menge').allTextContents())[1] === '60 ml');
pruefe('Gerätschaften stehen am Getränk', await p.locator('.geraete.hell .gk').count() >= 3);
await p.click('.reihe [data-go=mix]'); await p.waitForSelector('.mix'); await ruhe(p);
pruefe('Mix-Ansicht deckt den ganzen Bildschirm', await Zs(p, () => { const r = document.querySelector('.mix').getBoundingClientRect(); return r.top === 0 && Math.round(r.height) === innerHeight; }));
pruefe('Schritt 1 nennt seine Zutaten (Gurke, Sirup) und Geräte (Stößel)', await Zs(p, () => { const t = document.querySelector('.mix .braucht')?.textContent || ''; return /Salatgurke/.test(t) && /Holunderblütensirup/.test(t) && /Stößel/.test(document.querySelector('.mix .geraete')?.textContent || ''); }));
pruefe('Weiter und Zurück sind 46 px hoch', await Zs(p, () => Math.round(document.querySelector('.mix .weiter').getBoundingClientRect().height) >= 46));
await p.click('.mix .weiter'); await ruhe(p);
pruefe('Weiter blättert auf Schritt 2', /2 von 5/.test(await p.locator('.mixnr').textContent()));
await p.keyboard.press('ArrowLeft'); await ruhe(p);
pruefe('Pfeiltaste blättert zurück', /1 von 5/.test(await p.locator('.mixnr').textContent()));
await p.click('[data-a=mixkopf]'); await ruhe(p);
pruefe('Kopfzeile der Mix-Ansicht klappt ein', await p.locator('.mix.kopfzu').count() === 1 && await p.locator('.mix .oben b').count() === 0);
await p.keyboard.press('Escape'); await ruhe(p);
pruefe('Esc schließt die Mix-Ansicht', await Zs(p, () => __mixarium.zustand.view === 'getraenk'));
await p.click('[data-a=einkauf-dazu]'); await ruhe(p);
await p.click('.fl-griff'); await ruhe(p);
pruefe('fliegende Leiste öffnet ihre Bereiche', await p.locator('.fl-knoepfe [data-go]').count() === 5);
await p.click('.fl-knoepfe [data-go=einkauf]'); await ruhe(p);
pruefe('Einkaufsliste hat die 6 Zutaten für 3 Portionen', await p.locator('.posten').count() === 6 && /36 cl/.test(await p.locator('.posten').allTextContents().then((t) => t.join('|'))));
await p.click('.posten >> nth=0'); await ruhe(p);
pruefe('Abhaken wird gemerkt', await Zs(p, () => __mixarium.sammlung.einkauf.filter((x) => x.ok).length === 1));
await p.waitForTimeout(300); await p.reload(); await p.waitForSelector('.karte');
pruefe('nach dem Neuladen ist alles noch da', await p.locator('.karte').count() === 7 && await Zs(p, () => __mixarium.sammlung.einkauf.length === 6));
await p.click('.kopf [data-a=neu]'); await p.fill('[name=name]', 'Testlimo'); await p.fill('[name=ings]', '4 cl Zitronensaft\n1/2 Stück Limette\nEis'); await p.fill('[name=steps]', 'Alles schütteln.\nAbseihen.'); await p.click('#ed [type=submit]'); await ruhe(p);
pruefe('neues Getränk: Menge, Einheit und Name getrennt, eigene Kennung, kein Beispiel', await Zs(p, () => { const r = __mixarium.sammlung.getraenke[0]; return r.name === 'Testlimo' && r.ings[0].amt === '4' && r.ings[0].unit === 'cl' && r.ings[2].name === 'Eis' && r.uid && !r.beispiel; }));
await p.click('.zurueck'); await ruhe(p);
await p.click('.fl-griff'); await p.click('.fl-knoepfe [data-go=mehr]'); await ruhe(p);
await p.click('[data-a=beispiele-weg]'); await ruhe(p); await p.click('[data-a=fenster-ja]'); await ruhe(p);
pruefe('„Alle Beispiele löschen“ lässt nur das eigene Getränk stehen', await Zs(p, () => __mixarium.sammlung.getraenke.map((r) => r.name).join() === 'Testlimo'));
await p.click('.fl-griff'); await p.click('.fl-knoepfe [data-go=mehr]'); await ruhe(p);
await p.click('[data-a=alk]'); await ruhe(p); await p.click('[data-a=beispiele]'); await p.waitForSelector('[data-paket]');
pruefe('mit „Ohne Alkohol“ wird das Alkohol-Paket nicht angeboten', await p.locator('[data-paket]').count() === 1 && await p.locator('[data-paket=getraenke-mit-alkohol-fuer-mixarium]').count() === 0);
await p.context().close();

console.log('Monitor 1280 px, Übernahme aus der bisherigen App');
p = await seite(1280, 800);
await p.goto(U + 'impressum.html');
await Zs(p, () => { localStorage.setItem('mix9m', JSON.stringify([{ id: 1, name: 'Alter Mojito', cat: 'ckt', ings: [{ amt: '4 cl', unit: '', name: 'Rum' }], steps: [{ txt: 'Rühren.' }], servings: 2 }, { id: 2, name: 'Alte Limo', cat: 'limo', ings: [], steps: [] }])); localStorage.setItem('mxNoAlc9', '1'); localStorage.setItem('mxkey9m', 'sk-geheim-123'); });
const altVorher = await Zs(p, () => localStorage.getItem('mix9m'));
await p.goto(U + 'neu/'); await p.waitForSelector('.karte'); await ruhe(p);
pruefe('beide alten Getränke sind übernommen, „4 cl“ ist getrennt', await Zs(p, () => { const g = __mixarium.sammlung.getraenke; return g.length === 2 && g.find((r) => r.name === 'Alter Mojito').ings[0].unit === 'cl'; }));
pruefe('der Schalter „Ohne Alkohol“ kommt mit: nur 1 Karte sichtbar', await p.locator('.karte').count() === 1 && await Zs(p, () => __mixarium.sammlung.einstellungen.ohneAlkohol === true));
pruefe('der KI-Schlüssel ist NICHT übernommen', await Zs(p, () => !JSON.stringify(__mixarium.sammlung).includes('geheim')));
pruefe('die alten Daten sind unverändert', await Zs(p, () => localStorage.getItem('mix9m')) === altVorher && await Zs(p, () => localStorage.getItem('mxkey9m') === 'sk-geheim-123'));
pruefe('die alte Datenbank ist beim Nachsehen nicht entstanden', await Zs(p, async () => !(await indexedDB.databases()).some((d) => d.name === 'MeinMxBackup1')));
pruefe('am Monitor steht die Leiste links', await p.locator('.mx.breit .nav').count() === 1 && await p.locator('.fl-griff').count() === 0);
await p.click('.karte >> nth=0'); await ruhe(p);
pruefe('Liste links, Getränk rechts', await p.locator('.md .liste').count() === 1 && await p.locator('.md .detail').count() === 1);
await p.click('[data-a=fokus]'); await ruhe(p);
pruefe('„Nur dieses Getränk“ blendet Liste und Leiste aus', await p.locator('.md .liste').count() === 0 && await p.locator('.nav').count() === 0);
pruefe('die App füllt den Bildschirm genau', await Zs(p, () => Math.round(document.querySelector('.mx').getBoundingClientRect().height) === innerHeight));
await p.context().close();
pruefe('keine Fehler in der Konsole', fehler.length === 0, fehler.join(' | '));
await b.close(); server.close();
console.log(`\n${gruen} grün · ${rot} ROT`);
process.exit(rot ? 1 : 0);
